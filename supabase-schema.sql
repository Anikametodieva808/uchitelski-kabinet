create table if not exists public.resources (
 id bigint generated by default as identity primary key,
 title text not null,
 category text not null default 'Други',
 type text not null default 'Учебен материал',
 description text not null default '',
 url text not null default '',
 created_by uuid not null references auth.users(id) on delete cascade,
 author_email text,
 created_at timestamptz not null default now()
);
alter table public.resources enable row level security;
create policy "Anyone can read resources" on public.resources for select using (true);
create policy "Signed-in users can add resources" on public.resources for insert to authenticated with check (auth.uid()=created_by);
create policy "Authors can update their resources" on public.resources for update to authenticated using (auth.uid()=created_by) with check (auth.uid()=created_by);
create policy "Authors can delete their resources" on public.resources for delete to authenticated using (auth.uid()=created_by);
grant select on public.resources to anon, authenticated;
grant insert,update,delete on public.resources to authenticated;
grant usage,select on sequence public.resources_id_seq to authenticated;
